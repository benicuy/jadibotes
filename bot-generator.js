// ============ BOT GENERATOR ============

let selectedBotType = null;
let generatedCode = '';

function selectBotType(type) {
    selectedBotType = type;
    
    const waCard = document.getElementById('type-wa');
    const tgCard = document.getElementById('type-tg');
    
    if (waCard) waCard.classList.toggle('selected-wa', type === 'wa');
    if (tgCard) tgCard.classList.toggle('selected-tg', type === 'tg');
    
    renderBotConfigForm();
}

function renderBotConfigForm() {
    const container = document.getElementById('bot-config-form');
    if (!container) return;
    
    const config = getConfig();
    const prefix = config.prefix;
    const menus = getMenus();
    const availableMenus = menus.filter(m => m.type === 'all' || m.type === selectedBotType);
    
    let menuListHtml = '<div class="form-group"><label>Pilih Menu yang Aktif</label><div style="display:flex;flex-wrap:wrap;gap:8px;">';
    availableMenus.forEach(menu => {
        menuListHtml += `<label style="display:flex;align-items:center;gap:6px;"><input type="checkbox" class="menu-checkbox" value="${menu.command}" checked> ${prefix}${menu.command}</label>`;
    });
    menuListHtml += '</div></div>';
    
    if (selectedBotType === 'wa') {
        container.innerHTML = `
            <div class="card">
                <div class="card-title">⚙️ Konfigurasi WhatsApp Bot</div>
                <div class="form-group"><label>Nama Bot</label><input type="text" id="bot-name" value="MyWABot"></div>
                <div class="form-group"><label>Nomor Owner (62xxx)</label><input type="text" id="bot-owner" value="628123456789"></div>
                <div class="form-group"><label>Library</label><select id="bot-lib"><option value="baileys">Baileys</option><option value="wwebjs">whatsapp-web.js</option></select></div>
                <div class="form-group"><label>Pesan Selamat Datang</label><textarea id="bot-welcome">Halo! Gunakan ${prefix}help untuk bantuan.</textarea></div>
                ${menuListHtml}
            </div>
        `;
    } else if (selectedBotType === 'tg') {
        container.innerHTML = `
            <div class="card">
                <div class="card-title">⚙️ Konfigurasi Telegram Bot</div>
                <div class="form-group"><label>Nama Bot</label><input type="text" id="bot-name" value="MyTGBot"></div>
                <div class="form-group"><label>Bot Token (dari @BotFather)</label><input type="password" id="bot-token" placeholder="1234567890:ABCdef..."></div>
                <div class="form-group"><label>Pesan /start</label><textarea id="bot-start">Halo! Gunakan ${prefix}help untuk bantuan.</textarea></div>
                ${menuListHtml}
            </div>
        `;
    }
}

function generateBotCode() {
    if (!selectedBotType) return notify('Pilih tipe bot dulu!', 'error');
    if (!canCreateBot()) return;
    
    const name = document.getElementById('bot-name')?.value || 'Bot';
    const config = getConfig();
    const prefix = config.prefix;
    const menus = getMenus();
    
    // Get selected menus
    const selectedMenus = [];
    document.querySelectorAll('.menu-checkbox:checked').forEach(cb => {
        selectedMenus.push(cb.value);
    });
    
    const activeMenus = menus.filter(m => selectedMenus.includes(m.command));
    
    let code = `// Bot: ${name}\n// Prefix: ${prefix}\n// Generated by BotForge\n\n`;
    code += `const PREFIX = '${prefix}';\n\n`;
    code += `const commands = {\n`;
    activeMenus.forEach(menu => {
        const cmdCode = menu.code || `return "📌 ${menu.description}";`;
        code += `  '${menu.command}': () => { ${cmdCode} },\n`;
    });
    code += `};\n\n`;
    code += `function handleCommand(cmd, args) {\n  if (commands[cmd]) return commands[cmd](args);\n  return "Perintah tidak dikenal. Ketik ${PREFIX}help untuk bantuan.";\n}\n\n`;
    code += `console.log('✅ Bot ${name} siap dengan prefix ${prefix}');\n`;
    code += `module.exports = { handleCommand, commands };\n`;
    
    generatedCode = code;
    
    const outputContainer = document.getElementById('generated-code');
    if (outputContainer) {
        outputContainer.innerHTML = `<pre style="background:var(--bg3);padding:20px;border-radius:12px;overflow:auto;font-family:'DM Mono',monospace;font-size:12px;">${escapeHtml(code)}</pre>`;
        outputContainer.style.display = 'block';
    }
    
    // Show save button
    const saveContainer = document.getElementById('save-bot-section');
    if (saveContainer) saveContainer.style.display = 'block';
    
    notify('Kode berhasil digenerate!', 'success');
}

function saveBot() {
    if (!generatedCode) return notify('Generate kode bot dulu!', 'error');
    if (!canCreateBot()) return;
    
    const name = document.getElementById('bot-name')?.value || 'Bot Tanpa Nama';
    const type = selectedBotType;
    const lib = document.getElementById('bot-lib')?.value || 'baileys';
    
    const newBot = {
        id: Date.now(),
        userId: currentUser.id,
        name: name,
        type: type,
        lib: lib,
        code: generatedCode,
        createdAt: new Date().toISOString(),
        status: 'saved'
    };
    
    addBot(newBot);
    notify(`Bot "${name}" berhasil disimpan!`, 'success');
    
    // Reset form
    generatedCode = '';
    const outputContainer = document.getElementById('generated-code');
    if (outputContainer) outputContainer.style.display = 'none';
    const saveContainer = document.getElementById('save-bot-section');
    if (saveContainer) saveContainer.style.display = 'none';
    
    // Refresh bot list
    if (typeof renderMyBots === 'function') renderMyBots();
    if (typeof updateDashboard === 'function') updateDashboard();
}

function escapeHtml(text) {
    const div = document.createElement('div');
    div.textContent = text;
    return div.innerHTML;
}
